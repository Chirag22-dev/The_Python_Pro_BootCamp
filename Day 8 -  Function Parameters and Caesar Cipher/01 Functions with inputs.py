# Function definition
# This function prints a simple greeting message
def greet():
    print("Hello World")

# Function call
# Executes the greet() function
greet()


# Function definition with one parameter
# 'name' is a parameter (it receives a value when the function is called)
def greet_with_name(name):
    # Prints a greeting using the provided name
    print(f"Hello {name}")

# Function call with an argument
# "chirag" is an argument (the actual value passed to the function)
greet_with_name("chirag")
